// Regenerates packages/core/src/pptxTableStyles.data.ts: PowerPoint's own markup for its 74 built-in
// table styles, as captured by pptx-ts (MIT, © 2015-2022 Brent Ely, © 2026 shbernal) from a deck
// PowerPoint saved with one table per style:
//
//   node scripts/import-table-styles.mjs [path/to/pptx-ts/src/gen/pres/builtin-table-styles.ts]
//
// Without a path it reads the pinned commit below. PowerPoint names a built-in style by its GUID and
// writes its definition into ppt/tableStyles.xml only when it saved the deck itself; files from other
// tools often name the GUID alone, so the importer carries the definitions.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const COMMIT = '3f79aca28eb0ef2717afb9ec27a632cb5ae9da78';
const URL = `https://raw.githubusercontent.com/shbernal/pptx-ts/${COMMIT}/src/gen/pres/builtin-table-styles.ts`;
const source = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(URL)).text();

const block = (name) => {
  const m = source.match(new RegExp(`const ${name}[^=]*=\\s*\\[([\\s\\S]*?)\\n\\]`));
  if (!m) throw new Error(`no ${name} in the source`);
  return m[1];
};
const bodies = [...block('BODIES').matchAll(/^\t'(.*)',?$/gm)].map((m) => m[1].replace(/\\'/g, "'"));
const styles = [...block('STYLES').matchAll(/^\t\[(.*)\],?$/gm)].map((m) => JSON.parse(`[${m[1].replace(/'/g, '"')}]`));
if (styles.length !== 74) throw new Error(`expected 74 styles, read ${styles.length}`);
for (const [id, , index] of styles) if (!bodies[index]) throw new Error(`${id} names body ${index}, which is missing`);
for (const b of bodies) if (/<[^a/!]|<\/[^a]/.test(b.replace(/<\/?a:/g, ''))) throw new Error('a body uses a namespace other than a:');

const out = `// Generated by scripts/import-table-styles.mjs from pptx-ts ${COMMIT.slice(0, 7)} (MIT, © 2015-2022 Brent Ely, © 2026 shbernal); do not edit by hand.
// PowerPoint's own a:tblStyle children for its 74 built-in table styles; \`$0\` / \`$1\` take the
// scheme colour a family varies by.

/** Style bodies, the children of \`a:tblStyle\` in the DrawingML namespace (prefix \`a\`). */
export const TABLE_STYLE_BODIES: readonly string[] = ${JSON.stringify(bodies, null, 2)};

/** \`[styleId, styleName, body index, ...slot colours]\`. */
export const TABLE_STYLES: readonly (readonly [string, string, number, ...string[]])[] = [
${styles.map((s) => `  ${JSON.stringify(s)},`).join('\n')}
];
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../packages/core/src/pptxTableStyles.data.ts'), out);
console.log(`${styles.length} styles, ${bodies.length} bodies`);
